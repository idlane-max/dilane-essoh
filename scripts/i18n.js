    const reverseTranslations = new Map(
        Object.entries(translations).map(([source, translated]) => [translated, source])
    );
    const originalText = new WeakMap();
    const originalAttributes = new WeakMap();
    let language = 'fr';
    try {
        language = localStorage.getItem('portfolio-language') === 'en' ? 'en' : 'fr';
    } catch (error) {
        console.warn('Language preference could not be loaded:', error);
    }

    function translateValue(value) {
        const phrase = value.trim();
        return language === 'en'
            ? translations[phrase] || value
            : reverseTranslations.get(phrase) || value;
    }

    function apply(root = document.body) {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (!originalText.has(node)) {
                originalText.set(node, node.nodeValue);
            }

            const original = originalText.get(node);
            const leading = original.match(/^\s*/)?.[0] || '';
            const trailing = original.match(/\s*$/)?.[0] || '';
            const phrase = original.trim().replace(/\s+/g, ' ');
            node.nodeValue = leading + translateValue(phrase) + trailing;
        }

        const attributes = ['aria-label', 'aria-description', 'placeholder', 'title', 'alt', 'value'];
        root.querySelectorAll('*').forEach(element => {
            let originals = originalAttributes.get(element);
            if (!originals) {
                originals = new Map();
                originalAttributes.set(element, originals);
            }
            attributes.forEach(attribute => {
                if (!element.hasAttribute(attribute)) return;
                if (!originals.has(attribute)) {
                    originals.set(attribute, element.getAttribute(attribute));
                }
                element.setAttribute(attribute, translateValue(originals.get(attribute)));
            });
        });
    }

    function setLanguage(nextLanguage) {
        if (nextLanguage !== 'fr' && nextLanguage !== 'en') return;
        language = nextLanguage;
        document.documentElement.lang = language;
        try {
            localStorage.setItem('portfolio-language', language);
        } catch (error) {
            console.warn('Language preference could not be saved:', error);
        }
        document.querySelectorAll('[data-language]').forEach(button => {
            const selected = button.dataset.language === language;
            button.setAttribute('aria-pressed', String(selected));
        });
        apply(document.head);
        apply(document.body);
        document.dispatchEvent(new CustomEvent('site-language-change', {
            detail: { language }
        }));
    }

    window.siteI18n = {
        apply,
        get language() {
            return language;
        },
        setLanguage,
        t: translateValue
    };

    document.addEventListener('click', event => {
        const button = event.target.closest('[data-language]');
        if (button) setLanguage(button.dataset.language);
    });

    document.addEventListener('DOMContentLoaded', () => setLanguage(language));
